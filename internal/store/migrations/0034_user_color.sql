--
-- 这一列存的不是颜色值，是一个**词**：'' / blue / green / orange / red / purple / brown。
-- 页面按这个词去 CSS 里取对应的类（style.css 的 .pt-*），所以：
--   · 库里进不了任何样式文本——没有 url()、没有分号、没有花括号可写，注入面为零；
--   · 换配色只改 CSS，不用动数据；每个人自己的九格配色（0030）照样能盖在上面。
--
-- '' 是"跟着积分自动走"：后台每次重算积分时按管理员设的档位改写它（internal/api/points.go），
-- 于是绝大多数人从不需要有人去点这个按钮。purple 与 brown 是**只有管理员能设**的两个锁：
-- 一旦被设上，自动那一路就不碰它——"他是管理员"和"他被处罚"是状态，不是活跃度的读数，
-- 让一个数把这两件事冲掉是没有道理的。想让它重新自动跟分，把这一列清回 ''（控制台上是
-- "跟着积分自动"那个选项）。
