-- 为什么放在 users 而不是从 points 现算：颜色要出现在排行榜、动态、帖子、提交列表——那些
-- 视图本来就在读 users 这一行，多带一列是免费的；现算则要把档位判断复制到每一处渲染，
-- 一旦管理员调了档位，就会有几处忘了跟着改。
