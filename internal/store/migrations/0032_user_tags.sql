-- 0032: 用户标签。管理员给人贴的话，显示在名字后面：admin [作弊者]。
--
-- 为什么是一列文本而不是 tag 表 + 关联表：这个名字要出现在提交列表、排行榜、动态、帖子、
-- 评论、工单、关注列表——每一处都已经在读 users 那一行。做成关联表就意味着每个视图要么多一次
-- 查询、要么多一次 JOIN + GROUP 折叠，而这个东西最多三个短词。一列文本让它可以被折进
-- personSQL 那一条表达式里（store/user.go），于是"显示标签"这件事在所有视图里都是零成本。
--
-- 代价说清楚：按标签反查人（"把贴着作弊者的的人都列出来"）要用 LIKE，不漂亮；但今天没有
-- 这个需求，而"每个人名字后面那两个词"是每次渲染都要付的账。真要建表时，这一列还能当迁移素材。
--
-- 格式：多个标签用英文逗号分隔，每个不超过 12 个字符，整串最长 48。校验在写入侧
-- （store.SetUserTags）与读出侧（ParseTags 再挡一遍）各做一次——这一列会进 HTML，
-- 转义由 html/template 负责，但方括号与逗号是这套格式自己的分隔符，不能由人塞进来。
--
-- 注销账号时这一列跟着抹掉（身份的一部分，不是行为记录），见 CancelAccount。
ALTER TABLE users ADD COLUMN tags TEXT NOT NULL DEFAULT '';
